use super::*;

fn out(name: &str) -> String {
    std::env::temp_dir().join(format!("solidcraft-print-{}-{name}", std::process::id())).to_string_lossy().into_owned()
}

const KLIPPER_02: &str = r#"{"layer_height": 0.2, "initial_layer_print_height": 0.2, "gcode_flavor": "klipper"}"#;

#[test]
fn a_box_slices_to_gcode_on_disk() {
    let mut s = Session::default();
    run(&mut s, "solid.box", json!({"length": 20, "width": 20, "height": 20}));
    let path = out("box.gcode");
    let settings: Value = serde_json::from_str(KLIPPER_02).unwrap();
    let r = run(&mut s, "print.slice", json!({"path": path, "settings": settings}));
    assert_eq!(r["layers"], 100, "{r}");
    assert!(r["time_s"].as_f64().unwrap() > 60.0, "{r}");
    assert!(r["filament_g"].as_f64().unwrap() > 1.0, "{r}");
    assert!(r["slicer"].as_str().unwrap().starts_with("SlicerX"), "{r}");
    let text = std::fs::read_to_string(&path).unwrap();
    assert!(text.starts_with("; generated by SlicerX"), "{}", &text[..80]);
    assert!(text.lines().any(|l| l.starts_with("G1 ") && l.contains('E')), "no extruding move");
    assert_eq!(r["bytes"].as_u64().unwrap(), text.len() as u64);
    std::fs::remove_file(&path).ok();
}

#[test]
fn the_settings_file_is_read_and_inline_settings_lie_over_it() {
    let mut s = Session::default();
    run(&mut s, "solid.box", json!({"length": 10, "width": 10, "height": 24}));
    let config = out("plus4.json");
    std::fs::write(&config, r#"{"layer_height": 0.3, "initial_layer_print_height": 0.3, "gcode_flavor": "klipper"}"#).unwrap();
    let path = out("file.gcode");
    let r = run(&mut s, "print.slice", json!({"path": path, "config": config}));
    assert_eq!(r["layers"], 80, "{r}");
    let r = run(&mut s, "print.slice", json!({"path": path, "config": config, "settings": {"layer_height": 0.2, "initial_layer_print_height": 0.2}}));
    assert_eq!(r["layers"], 120, "{r}");
    // The slicer's own preflight refuses what no printer can run: a layer as tall as the line is wide.
    let r = s.execute("print.slice", &json!({"path": path, "config": config, "settings": {"layer_height": 0.4, "initial_layer_print_height": 0.4}}));
    assert!(r.is_err(), "{r:?}");
    std::fs::remove_file(&path).ok();
    std::fs::remove_file(&config).ok();
}

#[test]
fn only_the_named_bodies_are_sliced() {
    let mut s = Session::default();
    run(&mut s, "solid.box", json!({"length": 10, "width": 10, "height": 10}));
    run(&mut s, "solid.cylinder", json!({"radius": 5, "height": 30, "center": [40, 0, 0]}));
    let names: Vec<String> = s.world_state().bodies.iter().map(|b| b.name.clone()).collect();
    assert_eq!(names.len(), 2, "{names:?}");
    let path = out("one.gcode");
    let settings: Value = serde_json::from_str(KLIPPER_02).unwrap();
    let both = run(&mut s, "print.slice", json!({"path": path, "settings": settings}));
    assert_eq!(both["layers"], 150, "{both}");
    let one = run(&mut s, "print.slice", json!({"path": path, "settings": settings, "bodies": [names[0]]}));
    assert_eq!(one["layers"], 50, "{one}");
    std::fs::remove_file(&path).ok();
}

#[test]
fn bad_requests_are_refused_and_nothing_is_written() {
    let mut s = Session::default();
    let path = out("refused.gcode");
    assert!(s.execute("print.slice", &json!({"path": path})).is_err(), "no bodies");
    run(&mut s, "solid.box", json!({"length": 10, "width": 10, "height": 10}));
    let missing = out("missing.json");
    let not_object = out("list.json");
    std::fs::write(&not_object, "[1, 2]").unwrap();
    for p in [
        json!({"path": ""}),
        json!({"path": 7}),
        json!({"path": path, "bodies": ["nobody"]}),
        json!({"path": path, "config": missing}),
        json!({"path": path, "config": not_object}),
        json!({"path": path, "settings": 7}),
        json!({"path": path, "config": 7}),
        json!({"path": path, "config": [""]}),
    ] {
        assert!(s.execute("print.slice", &p).is_err(), "{p}");
    }
    assert!(!std::path::Path::new(&path).exists());
    std::fs::remove_file(&not_object).ok();
}

#[test]
fn settings_come_from_several_files_that_may_not_share_a_key() {
    let mut s = Session::default();
    run(&mut s, "solid.box", json!({"length": 10, "width": 10, "height": 20}));
    let printer = out("printer.json");
    let process = out("process.json");
    std::fs::write(&printer, r#"{"gcode_flavor": "klipper", "printable_height": 100}"#).unwrap();
    std::fs::write(&process, r#"{"layer_height": 0.2, "initial_layer_print_height": 0.2, "no_such_setting": true}"#).unwrap();
    let path = out("files.gcode");
    let r = run(&mut s, "print.slice", json!({"path": path, "config": [printer, process]}));
    assert_eq!(r["layers"], 100, "{r}");
    assert_eq!(r["ignored"], json!(["no_such_setting"]), "{r}");
    assert_eq!(r["refused"], json!([]), "{r}");
    // A value the slicer cannot use is reported, not fatal.
    let r = run(&mut s, "print.slice", json!({"path": path, "config": [printer, process], "settings": {"support_object_xy_distance": "50%"}}));
    assert_eq!(r["refused"][0]["key"], "support_object_xy_distance", "{r}");
    // The same key in two files is an error, so a key always has one home.
    let twice = out("twice.json");
    std::fs::write(&twice, r#"{"layer_height": 0.3}"#).unwrap();
    let r = s.execute("print.slice", &json!({"path": path, "config": [printer, process, twice]}));
    assert!(r.is_err(), "{r:?}");
    // A part taller than the printer is refused and nothing is written.
    std::fs::remove_file(&path).ok();
    run(&mut s, "solid.box", json!({"length": 10, "width": 10, "height": 150, "center": [50, 0, 0]}));
    let r = s.execute("print.slice", &json!({"path": path, "config": [printer, process]}));
    assert!(r.is_err(), "{r:?}");
    assert!(!std::path::Path::new(&path).exists());
    for f in [printer, process, twice] {
        std::fs::remove_file(f).ok();
    }
}

#[test]
fn the_session_holds_the_slice_for_preview_and_save_until_the_design_changes() {
    let mut s = Session::default();
    assert!(s.execute("print.preview", &json!({})).is_err(), "a preview before any slice");
    assert!(s.execute("print.save", &json!({"path": out("none.gcode")})).is_err(), "a save before any slice");
    run(&mut s, "solid.box", json!({"length": 20, "width": 20, "height": 20}));
    let settings: Value = serde_json::from_str(KLIPPER_02).unwrap();
    // No path: the slice is held, nothing is written.
    let r = run(&mut s, "print.slice", json!({"settings": settings}));
    assert_eq!(r["layers"], 100, "{r}");
    assert!(r.get("path").is_none(), "{r}");
    assert!(r["segments"].as_u64().unwrap() > 1000, "{r}");
    let held = s.print_slice().unwrap_or_else(|| panic!("no held slice"));
    assert_eq!(held.sliced.toolpaths.layers.len(), 100);
    assert_eq!(held.sliced.gcode.len() as u64, r["bytes"].as_u64().unwrap());

    let p = run(&mut s, "print.preview", json!({}));
    assert_eq!(p["stale"], false, "{p}");
    assert_eq!(p["layers"], 100);
    assert_eq!(p["bed"], json!([0.0, 0.0, 256.0, 256.0]), "{p}");
    assert_eq!(p["z"].as_array().unwrap().len(), 100);
    assert!(p["features"].as_array().unwrap().iter().any(|f| f["feature"] == "outer_wall"), "{}", p["features"]);
    assert!(p.get("layer").is_none());
    let one = run(&mut s, "print.preview", json!({"layer": 3}));
    let layer = &one["layer"];
    assert_eq!(layer["index"], 3);
    assert!((layer["z"].as_f64().unwrap() - 0.8).abs() < 1e-3, "{layer}");
    let paths = layer["paths"].as_array().unwrap();
    assert!(paths.iter().any(|p| p["feature"] == "outer_wall"), "{one}");
    assert!(paths.iter().all(|p| p["points"].as_array().unwrap().len() >= 2));
    assert!(s.execute("print.preview", &json!({"layer": 100})).is_err());
    assert!(s.execute("print.preview", &json!({"layer": -1})).is_err());

    let path = out("held.gcode");
    let w = run(&mut s, "print.save", json!({"path": path}));
    assert_eq!(w["bytes"], r["bytes"], "{w}");
    assert_eq!(w["stale"], false);
    let text = std::fs::read_to_string(&path).unwrap();
    assert!(text.starts_with("; generated by SlicerX"), "{}", &text[..80]);
    std::fs::remove_file(&path).ok();

    // The design changes: the held slice stays but is reported stale; undoing the change makes it current again.
    run(&mut s, "solid.box", json!({"length": 5, "width": 5, "height": 5, "center": [50, 0, 0]}));
    assert_eq!(run(&mut s, "print.preview", json!({}))["stale"], true);
    run(&mut s, "edit.undo", json!({}));
    assert_eq!(run(&mut s, "print.preview", json!({}))["stale"], false);
    // Slicing again replaces the held slice.
    run(&mut s, "solid.box", json!({"length": 5, "width": 5, "height": 30, "center": [50, 0, 15]}));
    let r2 = run(&mut s, "print.slice", json!({"settings": serde_json::from_str::<Value>(KLIPPER_02).unwrap()}));
    assert_eq!(r2["layers"], 150, "{r2}");
    assert_eq!(run(&mut s, "print.preview", json!({}))["layers"], 150);
    // A new design drops it.
    run(&mut s, "file.new", json!({}));
    assert!(s.print_slice().is_none());
}

#[test]
fn a_refused_slice_leaves_the_earlier_one_in_place() {
    let mut s = Session::default();
    run(&mut s, "solid.box", json!({"length": 20, "width": 20, "height": 20}));
    run(&mut s, "print.slice", json!({"settings": serde_json::from_str::<Value>(KLIPPER_02).unwrap()}));
    let r = s.execute("print.slice", &json!({"settings": {"layer_height": 0.4, "initial_layer_print_height": 0.4}}));
    assert!(r.is_err(), "{r:?}");
    assert_eq!(run(&mut s, "print.preview", json!({}))["layers"], 100);
}
