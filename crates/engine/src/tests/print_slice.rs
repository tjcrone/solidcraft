#[test]
fn the_design_keeps_its_own_print_settings_over_the_files_and_under_the_call() {
    let mut s = Session::default();
    run(&mut s, "solid.box", json!({"length": 10, "width": 10, "height": 24}));
    let config = out("overlay.json");
    std::fs::write(&config, r#"{"layer_height": "0.3", "initial_layer_print_height": "0.3", "gcode_flavor": "klipper"}"#).unwrap();
    // Nothing overridden: the files decide.
    let g = run(&mut s, "print.settings.get", json!({"config": config}));
    assert_eq!(g["settings"]["layer_height"]["source"], "file", "{g}");
    assert_eq!(g["settings"]["layer_height"]["value"], "0.3");
    assert_eq!(run(&mut s, "print.settings.get", json!({"config": config, "keys": ["wall_loops"]}))["settings"]["wall_loops"]["source"], "default");
    assert_eq!(run(&mut s, "print.slice", json!({"config": config}))["layers"], 80);
    // The design overrides the layer height: 0.2 mm makes 120 layers, and the change is undoable.
    let r = run(&mut s, "print.settings.set", json!({"set": {"layer_height": "0.2", "initial_layer_print_height": "0.2"}}));
    assert_eq!(r["overlay"]["layer_height"], "0.2", "{r}");
    assert_eq!(run(&mut s, "print.slice", json!({"config": config}))["layers"], 120);
    let g = run(&mut s, "print.settings.get", json!({"config": config, "keys": ["layer_height"]}));
    assert_eq!(g["settings"]["layer_height"]["source"], "design");
    assert!(s.is_dirty());
    // An explicit setting on the call still wins over the design.
    assert_eq!(
        run(&mut s, "print.slice", json!({"config": config, "settings": {"layer_height": 0.3, "initial_layer_print_height": 0.3}}))["layers"],
        80
    );
    run(&mut s, "edit.undo", json!({}));
    assert!(s.doc.print.overlay.is_empty());
    run(&mut s, "edit.redo", json!({}));
    assert_eq!(s.doc.print.overlay.len(), 2);
    // Null removes one key; clear removes the rest; bad keys and values are refused.
    run(&mut s, "print.settings.set", json!({"set": {"initial_layer_print_height": null}}));
    assert_eq!(s.doc.print.overlay.len(), 1);
    for bad in [json!({}), json!({"set": {}}), json!({"set": {"Layer": 1}}), json!({"set": {"layer_height": {"a": 1}}}), json!({"set": 5})] {
        assert!(s.execute("print.settings.set", &bad).is_err(), "{bad}");
    }
    assert_eq!(run(&mut s, "print.settings.clear", json!({}))["overlay"], json!({}));
    // The overlay survives a save and a load.
    run(&mut s, "print.settings.set", json!({"set": {"sparse_infill_density": "20%", "enable_support": "1"}}));
    let text = serde_json::to_string(&*s.doc).unwrap();
    assert!(text.contains("sparse_infill_density"), "{text}");
    let back: solidcraft_doc::Document = serde_json::from_str(&text).unwrap();
    assert_eq!(back.print.overlay.len(), 2);
    std::fs::remove_file(&config).ok();
}

#[test]
fn a_relative_path_is_refused_and_nothing_is_written() {
    let mut s = Session::default();
    run(&mut s, "solid.box", json!({"length": 10, "width": 10, "height": 10}));
    let settings: Value = serde_json::from_str(KLIPPER_02).unwrap();
    // The hostile-parameters test feeds strings like these; they used to land as G-code files in
    // whatever folder the process ran in.
    // Names no other run leaves behind, so an old stray file cannot pass for a new one.
    let fresh = |name: &str| format!("sc-relative-{}-{name}", std::process::id());
    for path in ["w = 20".to_string(), fresh("nope"), fresh("sub/dir.gcode"), format!("./{}", fresh("here.gcode"))] {
        let e = s.execute("print.slice", &json!({"path": path, "settings": settings})).unwrap_err().to_string();
        assert!(e.contains("absolute"), "{path}: {e}");
        assert!(path.starts_with("w = ") || !std::path::Path::new(&path).exists(), "{path} was written");
        assert!(s.print_slice().is_none(), "{path}: a refused slice is not held");
    }
    run(&mut s, "print.slice", json!({"settings": settings}));
    let later = fresh("later.gcode");
    let e = s.execute("print.save", &json!({"path": later})).unwrap_err().to_string();
    assert!(e.contains("absolute"), "{e}");
    assert!(!std::path::Path::new(&later).exists());
    let ok = out("absolute.gcode");
    assert_eq!(run(&mut s, "print.save", json!({"path": ok}))["path"], ok);
    std::fs::remove_file(&ok).ok();
}

#[test]
fn the_design_remembers_where_it_sits_on_the_bed() {
    let mut s = Session::default();
    run(&mut s, "solid.box", json!({"length": 20, "width": 10, "height": 5}));
    let settings: Value = serde_json::from_str(KLIPPER_02).unwrap();
    run(&mut s, "print.slice", json!({"settings": settings}));
    let centred = run(&mut s, "print.preview", json!({}));
    let bed = run(&mut s, "print.bed", json!({"config": []}));
    assert!(bed["bed"][2].as_f64().unwrap() > bed["bed"][0].as_f64().unwrap(), "{bed}");
    assert_eq!(bed["placement"], json!({"x": 0.0, "y": 0.0, "rotation": 0.0}));
    // Placing is undoable and saved with the design.
    let placed = run(&mut s, "print.place", json!({"x": 25, "y": -10}));
    assert_eq!(placed["placement"], json!({"x": 25.0, "y": -10.0, "rotation": 0.0}));
    assert!(s.print_slice().is_some_and(|h| h.stale(&s.doc)), "a new placement makes the slice stale");
    run(&mut s, "print.slice", json!({"settings": settings}));
    let moved = run(&mut s, "print.preview", json!({}));
    let (a, b) = (&centred["offset"], &moved["offset"]);
    assert!((b[0].as_f64().unwrap() - a[0].as_f64().unwrap() - 25.0).abs() < 1e-3, "{a} {b}");
    assert!((b[1].as_f64().unwrap() - a[1].as_f64().unwrap() + 10.0).abs() < 1e-3, "{a} {b}");
    assert_eq!(moved["placement"]["x"], 25.0);
    run(&mut s, "print.place", json!({"rotation": 90}));
    assert_eq!(s.doc.print.placement.rotation, 90.0);
    run(&mut s, "edit.undo", json!({}));
    assert_eq!(s.doc.print.placement.rotation, 0.0);
    assert_eq!(run(&mut s, "print.place", json!({"centre": true}))["placement"], json!({"x": 0.0, "y": 0.0, "rotation": 0.0}));
    for bad in [json!({"x": "far"}), json!({"x": 1e9}), json!({"rotation": 720}), json!({"y": [1]})] {
        assert!(s.execute("print.place", &bad).is_err(), "{bad}");
    }
    let text = serde_json::to_string(&*s.doc).unwrap();
    assert!(!text.contains("placement"), "a centred design saves no placement: {text}");
    run(&mut s, "print.place", json!({"x": 1}));
    assert!(serde_json::to_string(&*s.doc).unwrap().contains("\"placement\""));
}
